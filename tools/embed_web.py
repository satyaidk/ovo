#!/usr/bin/env python3
"""Embed web/index.html into the firmware as a gzipped byte array.

Why: the ESP32 serves the controller page straight from flash. Gzipping it
shrinks the page to roughly a quarter of its size, which saves flash and makes
the page load faster over Wi-Fi; every browser unpacks it transparently
because the firmware sends `Content-Encoding: gzip`.

Usage (from the repository root):
    python tools/embed_web.py           # regenerate src/web/WebUi.h
    python tools/embed_web.py --check   # exit 1 if WebUi.h is out of date (CI)

Edit web/index.html, never src/web/WebUi.h.
"""
import argparse
import gzip
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "web" / "index.html"
OUT = ROOT / "src" / "web" / "WebUi.h"

HEADER = """\
// WebUi.h - AUTO-GENERATED by tools/embed_web.py from web/index.html.
// Do not edit by hand: change web/index.html and run
//   python tools/embed_web.py
//
// The controller page, gzipped ({raw} bytes -> {packed} bytes). The firmware
// serves it with "Content-Encoding: gzip"; the browser unpacks it.
#pragma once
#include <stddef.h>
#include <stdint.h>
#include <pgmspace.h>

static const size_t INDEX_HTML_RAW_LEN = {raw};
static const size_t INDEX_HTML_GZ_LEN = {packed};
static const uint8_t INDEX_HTML_GZ[] PROGMEM = {{
{body}
}};
"""


def build() -> str:
    raw = SRC.read_bytes()
    packed = gzip.compress(raw, compresslevel=9, mtime=0)  # mtime=0: same input, same bytes
    lines = []
    for i in range(0, len(packed), 20):
        lines.append("  " + ",".join(f"0x{b:02x}" for b in packed[i:i + 20]) + ",")
    return HEADER.format(raw=len(raw), packed=len(packed), body="\n".join(lines))


def embedded_html() -> bytes:
    """Decompress the bytes currently stored in WebUi.h."""
    text = OUT.read_text(encoding="utf-8")
    body = text.split("PROGMEM = {", 1)[1].rsplit("};", 1)[0]
    data = bytes(int(h, 16) for h in re.findall(r"0x([0-9a-f]{2})", body))
    return gzip.decompress(data)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="verify WebUi.h matches web/index.html")
    args = ap.parse_args()

    if args.check:
        # Compare decompressed content, not bytes: zlib versions may pack differently.
        if not OUT.exists() or embedded_html() != SRC.read_bytes():
            print("src/web/WebUi.h is out of date: run python tools/embed_web.py", file=sys.stderr)
            return 1
        print("src/web/WebUi.h is up to date")
        return 0

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(build(), encoding="utf-8", newline="\n")
    raw, packed = SRC.stat().st_size, len(gzip.compress(SRC.read_bytes(), 9, mtime=0))
    print(f"wrote {OUT.relative_to(ROOT)}: {raw} bytes -> {packed} bytes gzipped")
    return 0


if __name__ == "__main__":
    sys.exit(main())
